package invariants

import (
	"go/token"
	"strings"
	"testing"
	"testing/fstest"
)

func fuzzViolations(t *testing.T, rel, src string) []Violation {
	t.Helper()
	return checkSourceWith([]Rule{fuzzEntryPoints}, token.NewFileSet(), rel, []byte(src))
}

const fuzzDecodeSrc = `package ws
import "encoding/json"
func %s(raw []byte) error { var v any; return json.Unmarshal(raw, &v) }
`

func fuzzDecodeIn(name string) string { return strings.Replace(fuzzDecodeSrc, "%s", name, 1) }

func TestFuzzEntryPoints_UnlistedDecoderIsFlagged(t *testing.T) {
	got := fuzzViolations(t, "ws/new_payload.go", fuzzDecodeIn("parseBrandNewPayload"))
	if len(got) != 1 || !strings.Contains(got[0].Msg, "ws.parseBrandNewPayload") {
		t.Fatalf("want one violation naming ws.parseBrandNewPayload, got %v", got)
	}
}

func TestFuzzEntryPoints_ListedDecoderMovedToAnotherFileStillMatches(t *testing.T) {
	if got := fuzzViolations(t, "ws/some_other_file.go", fuzzDecodeIn("parseChatSend")); len(got) != 0 {
		t.Fatalf("a listed function in a new file of the same package must still match, got %v", got)
	}
}

func TestFuzzEntryPoints_SameNameInAnotherPackageIsNotCovered(t *testing.T) {
	src := strings.Replace(fuzzDecodeIn("parseChatSend"), "package ws", "package api", 1)
	if got := fuzzViolations(t, "api/chat.go", src); len(got) != 1 {
		t.Fatalf("a row is keyed by package as well as name, got %v", got)
	}
}

func TestFuzzEntryPoints_GeneratedToolingAndExamplesAreSkipped(t *testing.T) {
	generated := "// Code generated by sqlc. DO NOT EDIT.\n\n" + fuzzDecodeIn("parseGenerated")
	if got := fuzzViolations(t, "ws/gen.go", generated); len(got) != 0 {
		t.Fatalf("a generated file must be skipped, got %v", got)
	}
	if got := fuzzViolations(t, "cmd/smoke/x.go", fuzzDecodeIn("parseSmoke")); len(got) != 0 {
		t.Fatalf("cmd/ must be skipped, got %v", got)
	}
	if got := fuzzViolations(t, "plugin/examples/hello/main.go", fuzzDecodeIn("parseHello")); len(got) != 0 {
		t.Fatalf("example plugins must be skipped, got %v", got)
	}
}

func TestFuzzEntryPoints_OtherDecodersAreSeen(t *testing.T) {
	cases := map[string]string{
		"aliased json": `package ws
import j "encoding/json"
func f(b []byte) { _ = j.NewDecoder(nil) }
`,
		"zip": `package ws
import "archive/zip"
func f() { _, _ = zip.NewReader(nil, 0) }
`,
		"image": `package ws
import "image"
func f() { _, _, _ = image.Decode(nil) }
`,
		"html": `package ws
import "golang.org/x/net/html"
func f() { _ = html.NewTokenizer(nil) }
`,
		"multipart method": `package ws
import "net/http"
func f(r *http.Request) { _, _, _ = r.FormFile("file") }
`,
		"dot import": `package ws
import . "encoding/json"
func f() {}
`,
	}
	for name, src := range cases {
		if got := fuzzViolations(t, "ws/x.go", src); len(got) != 1 {
			t.Errorf("%s: want one violation, got %v", name, got)
		}
	}
}

func TestFuzzEntryPoints_TableClosureIsKeyedByVariable(t *testing.T) {
	src := `package ws
import "encoding/json"
var commandConstructors = map[string]func([]byte) error{
	"x": func(b []byte) error { var v any; return json.Unmarshal(b, &v) },
}
var otherTable = map[string]func([]byte) error{
	"x": func(b []byte) error { var v any; return json.Unmarshal(b, &v) },
}
`
	got := fuzzViolations(t, "ws/command.go", src)
	if len(got) != 1 || !strings.Contains(got[0].Msg, "ws.otherTable") {
		t.Fatalf("want only the unlisted table flagged, got %v", got)
	}
}

func TestFuzzEntryPoints_TreeFlagsStaleRows(t *testing.T) {
	fsys := fstest.MapFS{
		"ws/frames.go": {Data: []byte("package ws\nfunc replayCopy(b []byte) []byte { return b }\n")},
	}
	tree := fuzzTree(fsys)
	msgs := make([]string, 0, len(tree))
	for _, v := range tree {
		msgs = append(msgs, v.Msg)
	}
	all := strings.Join(msgs, "\n")
	for _, want := range []string{
		"ws.replayCopy no longer decodes anything",
		"ws.parseChatSend names no function in the tree",
		"names fuzz target ws.FuzzCommandPayloads, which does not exist",
	} {
		if !strings.Contains(all, want) {
			t.Errorf("tree check missing %q in:\n%s", want, all)
		}
	}
}

func TestFuzzEntryPoints_TablesAreDisjointAndGapsMatchCeiling(t *testing.T) {
	for k := range FuzzGaps {
		if _, ok := FuzzEntryPoints[k]; ok {
			t.Errorf("%s is both a gap and covered", k)
		}
		if _, ok := FuzzTrustedDecodes[k]; ok {
			t.Errorf("%s is both a gap and trusted", k)
		}
	}
	if len(FuzzGaps) != fuzzGapCeiling {
		t.Errorf("len(FuzzGaps) = %d, fuzzGapCeiling = %d", len(FuzzGaps), fuzzGapCeiling)
	}
}
