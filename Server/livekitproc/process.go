// Process manages the companion livekit-server binary.
type Process struct {
	cfg        *config.VoiceConfig
	tlsCfg     *config.TLSConfig
	dataDir    string
	httpClient *http.Client // for health checks — no redirect following

	// restarts counts relaunches after an unexpected exit; gaveUp is set when the
	// backoff exhausted maxRetries. Both feed the attention panel and support bundle.
	restarts atomic.Int64
	gaveUp   atomic.Bool

	// timing is the restart backoff; tests shorten it.
	timing restartTiming
	// kick wakes a loop in the slow retry tier (Restart); one slot, so extra presses collapse.
	kick chan struct{}

	mu syncutil.Mutex
	// nextRetry is when the slow tier retries; zero while runLoop is not waiting
	// there. Guarded by mu so Restart and the loop agree whether a wake can land.
	nextRetry time.Time
	cmd       *exec.Cmd
	cancel    context.CancelFunc
	stopped   bool
	runDone   chan struct{} // closed by runLoop when cmd.Wait() returns
	loopDone  chan struct{} // closed when runLoop exits entirely
}

// New creates a process manager without starting it. tlsCfg reuses OwnCord's
// certs for LiveKit TLS (avoids mixed-content blocks in WebView2).
func New(cfg *config.VoiceConfig, tlsCfg *config.TLSConfig, dataDir string) *Process {
	return &Process{
		cfg:     cfg,
		tlsCfg:  tlsCfg,
		dataDir: dataDir,
		timing:  defaultRestartTiming,
		kick:    make(chan struct{}, 1),
		httpClient: &http.Client{
			// Own the transport: http.DefaultTransport's pool is shared, and
			// httptest.Server.Close closing its idle connections would sever in-flight health checks.
			Transport: http.DefaultTransport.(*http.Transport).Clone(),
			CheckRedirect: func(*http.Request, []*http.Request) error {
				return http.ErrUseLastResponse
			},
		},
	}
}

// autoGeneratedMarker marks a livekit.yaml written by OwnCord; one without it is user-managed and never
// overwritten.
const autoGeneratedMarker = "Auto-generated by OwnCord"

// liveKitStopGrace is how long Stop waits after the shutdown signal before killing; a var so tests can
// shorten it.
var liveKitStopGrace = 5 * time.Second

// generateConfig writes a minimal livekit.yaml. A file lacking the
// auto-generated marker is user-managed and left alone so operators can set
// options OwnCord does not model (ips.includes, interfaces, stun_servers).
func (p *Process) generateConfig() (string, error) {
	cfgPath := filepath.Join(p.dataDir, "livekit.yaml")

	if existing, err := os.ReadFile(cfgPath); err == nil {
		// An empty or whitespace-only file is a truncated leftover: regenerate rather than wedge LiveKit.
		if len(strings.TrimSpace(string(existing))) > 0 &&
			!strings.Contains(string(existing), autoGeneratedMarker) {
			slog.Info("livekit: livekit.yaml is user-managed (auto-generated marker absent), not overwriting", "path", cfgPath)
			slog.Warn("livekit: ensure the keys entry in your livekit.yaml matches voice.livekit_api_key / voice.livekit_api_secret")
			return cfgPath, nil
		}
	} else if !os.IsNotExist(err) {
		return "", fmt.Errorf("reading existing livekit config: %w", err)
	}

	// No TURN TLS config: signaling is proxied through OwnCord's HTTPS server at /livekit/*.

	// Reject YAML-breaking characters in credentials. The error names the field but
	// never echoes the byte: Start() logs it, which would write a credential byte to the log.
	const unsafeYAML = ":#{}\n\r\"\\"
	for _, cred := range []struct {
		field string
		value string
	}{
		{"voice.livekit_api_key", p.cfg.LiveKitAPIKey},
		{"voice.livekit_api_secret", p.cfg.LiveKitAPISecret},
	} {
		if strings.ContainsAny(cred.value, unsafeYAML) {
			return "", fmt.Errorf(`%s contains a character that cannot be safely written to livekit.yaml (one of : # { } " \ CR LF)`, cred.field)
		}
	}
	addrLines, err := rtcAddressLines(p.cfg)
	if err != nil {
		return "", err
	}
	// Emit exactly one port form: a port_range_start/end in the YAML wins over udp_port. The range is the
	// shipped default.
	rtcPortLines := "  port_range_start: 50000\n  port_range_end: 60000"
	if p.cfg.UDPPort > 0 {
		rtcPortLines = fmt.Sprintf("  udp_port: %d", p.cfg.UDPPort)
	}

	content := fmt.Sprintf(`# Auto-generated by OwnCord — regenerated on every server start.
# To manage this file yourself (custom rtc options, multiple interfaces, etc.),
# delete the first line above; OwnCord will then leave the file untouched.
# Your keys entry must still match voice.livekit_api_key /
# voice.livekit_api_secret in config.yaml.
port: 7880

rtc:
%s%s
  pli_throttle:
    low_quality: 500ms
    mid_quality: 1s
    high_quality: 1s

audio:
  active_level: 45
  min_percentile: 30
  update_interval: 100
  smooth_intervals: 1

keys:
  "%s": "%s"

logging:
  level: info
`, rtcPortLines, addrLines, p.cfg.LiveKitAPIKey, p.cfg.LiveKitAPISecret)

	if err := os.MkdirAll(p.dataDir, 0o750); err != nil {
		return "", fmt.Errorf("creating data dir: %w", err)
	}
	if err := os.WriteFile(cfgPath, []byte(content), 0o600); err != nil {
		return "", fmt.Errorf("writing livekit config: %w", err)
	}

	return cfgPath, nil
}

func rtcAddressLines(cfg *config.VoiceConfig) (string, error) {
	// A pinned node_ip replaces use_external_ip, since LiveKit overwrites node_ip
	// with its STUN result while that is on. advertise_internal_ip only works
	// alongside use_external_ip, so it keeps discovery on and the pin is ignored
	// (warned at start-up). Validate: a plain IP with no YAML-breaking chars.
	addrLine := ""
	if cfg.NodeIP != "" {
		for _, ch := range cfg.NodeIP {
			if ch == '"' || ch == '\\' || ch == '\n' || ch == '\r' || ch == '#' || ch == '{' || ch == '}' {
				return "", fmt.Errorf("node_ip contains unsafe character %q", string(ch))
			}
		}
		addrLine = fmt.Sprintf("\n  node_ip: %q", cfg.NodeIP)
	}
	if cfg.NodeIP == "" || cfg.AdvertiseInternalIP {
		addrLine = "\n  use_external_ip: true" + addrLine
	}
	// Advertise LAN host candidates so clients on the local network can reach a dual-homed server.
	advertiseInternalLine := ""
	if cfg.AdvertiseInternalIP {
		advertiseInternalLine = "\n  advertise_internal_ip: true"
	}
	return addrLine + advertiseInternalLine, nil
}

// Start launches the livekit-server binary. With no LiveKitBinaryPath and
// auto-download off it is a no-op (externally managed); with auto-download the
// binary is fetched and verified in the background so startup never blocks.
func (p *Process) Start() error {
	if p.cfg.LiveKitBinaryPath == "" && !p.cfg.AutoDownloadLiveKit {
		slog.Info("livekit: no binary path configured, assuming externally managed")
		return nil
	}

	p.mu.Lock()
	defer p.mu.Unlock()

	if p.cmd != nil {
		return fmt.Errorf("livekit process already running")
	}
	if p.loopDone != nil {
		select {
		case <-p.loopDone:
		default:
			return fmt.Errorf("livekit process already running")
		}
	}
	if p.stopped {
		return nil
	}

	cfgPath, err := p.generateConfig()
	if err != nil {
		return fmt.Errorf("generating livekit config: %w", err)
	}

	ctx, cancel := context.WithCancel(context.Background())
	p.cancel = cancel
	loopDone := make(chan struct{})
	p.loopDone = loopDone

	go func() {
		defer close(loopDone)

		binPath := p.cfg.LiveKitBinaryPath
		if binPath == "" {
			resolved, dlErr := p.resolveBinary(ctx)
			if dlErr != nil {
				if ctx.Err() == nil {
					slog.Error("livekit: auto-download failed — voice stays offline until livekit-server is available",
						"error", dlErr,
						"hint", "check the network, or set voice.livekit_binary in config.yaml to a binary you provide")
				}
				return
			}
			binPath = resolved
		}
		p.runLoop(ctx, cfgPath, binPath)
	}()

	return nil
}

// resolveBinary downloads or reuses the pinned release, retrying so a transient boot-time failure does not
// disable voice until restart.
func (p *Process) resolveBinary(ctx context.Context) (string, error) {
	const (
		attempts   = 3
		retryDelay = 15 * time.Second
	)
	var lastErr error
	for i := range attempts {
		if i > 0 {
			slog.Warn("livekit: retrying download", "attempt", i+1, "error", lastErr)
			select {
			case <-time.After(retryDelay):
			case <-ctx.Done():
				return "", ctx.Err()
			}
		}
		attemptCtx, cancel := context.WithTimeout(ctx, 10*time.Minute)
		path, err := EnsureBinary(attemptCtx, p.dataDir, p.cfg.LiveKitVersion)
		cancel()
		if err == nil {
			return path, nil
		}
		lastErr = err
	}
	return "", lastErr
}

// runLoop starts and restarts the process until stopped, with exponential
// backoff (3s doubling to 60s). After 10 rapid failures (exit within 30s) it
// drops to a slow tier: one try every 10 minutes, or at once on Restart.
func (p *Process) runLoop(ctx context.Context, cfgPath, binPath string) {
	tm := p.timing
	rapidFailures := 0
	delay := tm.baseDelay

	for {
		if ctx.Err() != nil {
			return
		}

		slog.Info("livekit: starting process",
			"binary", binPath,
			"config", cfgPath,
			"rapid_failures", rapidFailures)

		startTime := time.Now()
		live, err := p.runOnce(ctx, cfgPath, binPath)
		if !live {
			return
		}

		if time.Since(startTime) > tm.stableAfter {
			rapidFailures = 0
			delay = tm.baseDelay
			p.gaveUp.Store(false)
		} else {
			rapidFailures++
		}

		if err != nil {
			p.restarts.Add(1)
			slog.Error("livekit: process exited unexpectedly",
				"error", err,
				"rapid_failures", rapidFailures,
				"restart_delay", delay)
		}

		if rapidFailures >= tm.maxRetries {
			manual, ok := p.slowRetry(ctx, rapidFailures)
			if !ok {
				return
			}
			// A rapid failure after a timed attempt returns to the slow tier; an admin restart gets the fast tier
			// again.
			rapidFailures = tm.maxRetries - 1
			if manual {
				rapidFailures = 0
				p.gaveUp.Store(false)
			}
			delay = tm.baseDelay
			continue
		}

		select {
		case <-time.After(delay):
			slog.Info("livekit: restarting process")
		case <-ctx.Done():
			return
		}

		delay *= 2
		if delay > tm.maxDelay {
			delay = tm.maxDelay
		}
	}
}

func newLiveKitCmd(ctx context.Context, cfgPath, binPath string) *exec.Cmd {
	cmd := exec.CommandContext(ctx, binPath, "--config", cfgPath) //nolint:gosec // G204: binary path from trusted server config or verified download
	// Route stdout and stderr into slog (one writer each, as livekit-server uses
	// separate goroutines) so ICE, port and key errors reach the log views and support bundle.
	cmd.Stdout = &liveKitLogWriter{}
	cmd.Stderr = &liveKitLogWriter{}
	// Short graceful window, then os/exec kills and reaps before Stop lets an updater start a successor.
	cmd.Cancel = func() error { return stopLiveKitProcess(cmd.Process) }
	cmd.WaitDelay = liveKitStopGrace
	// Die with a parent that skipped its teardown (kill -9, OOM, force-exit)
	// instead of orphaning with 7880/UDP bound: Pdeathsig on Linux, a job object on
	// Windows via containLiveKitProcess.
	cmd.SysProcAttr = liveKitSysProcAttr()
	return cmd
}

func (p *Process) IsRunning() bool {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.cmd != nil && p.cmd.Process != nil
}

// PID returns the companion's process id; ok is false while none runs.
func (p *Process) PID() (int, bool) {
	p.mu.Lock()
	defer p.mu.Unlock()
	if p.cmd == nil || p.cmd.Process == nil {
		return 0, false
	}
	return p.cmd.Process.Pid, true
}

// HealthCheck probes the LiveKit HTTP endpoint; true on any response.
func (p *Process) HealthCheck(ctx context.Context) (bool, error) {
	httpURL := HTTPURL(p.cfg.LiveKitURL)

	ctx, cancel := context.WithTimeout(ctx, 3*time.Second)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, httpURL, nil)
	if err != nil {
		return false, fmt.Errorf("creating health check request: %w", err)
	}

	resp, err := p.httpClient.Do(req)
	if err != nil {
		return false, fmt.Errorf("livekit health check failed: %w", err)
	}
	_ = resp.Body.Close()

	return true, nil
}

// Stop stops the companion and waits until it has exited: graceful on Unix
// before WaitDelay forces a kill, immediate on Windows. Only runLoop calls
// cmd.Wait and concurrent Stops join it; returning unreaped would let an
// updater launch over its bound ports.
func (p *Process) Stop() {
	p.mu.Lock()
	p.stopped = true
	cancel := p.cancel
	done := p.runDone
	loopDone := p.loopDone
	p.mu.Unlock()

	if cancel != nil {
		cancel()
	}

	// Wait on runLoop's cmd.Wait() (closing runDone); a second Wait is unsafe on Windows.
	if done != nil {
		<-done
		slog.Info("livekit: process exited")
	}

	// Wait for the whole runLoop goroutine so no new iteration starts after Stop returns.
	if loopDone != nil {
		<-loopDone
	}
}

// HTTPURL converts a WebSocket URL to an HTTP URL; any other URL is returned as is.
func HTTPURL(wsURL string) string {
	switch {
	case len(wsURL) >= 6 && wsURL[:6] == "wss://":
		return "https://" + wsURL[6:]
	case len(wsURL) >= 5 && wsURL[:5] == "ws://":
		return "http://" + wsURL[5:]
	default:
		return wsURL
	}
}

// NewStoppableForTest returns a started-looking Process that runs onStop on Stop, so teardown order is
// testable without a binary.
func NewStoppableForTest(onStop func()) *Process {
	return &Process{cancel: onStop, kick: make(chan struct{}, 1)}
}
