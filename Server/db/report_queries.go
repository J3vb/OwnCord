// ReportEvidenceInput is one evidence row queued for FileReport's
// transaction, seq relative to the reported item (0).
type ReportEvidenceInput struct {
	Seq             int64
	MessageID       *int64
	AuthorID        int64
	Content         string
	AttachmentsJSON string
}

// ReportEvent is one row of report_events, this feature's own immutable
// history (second Codex review): action is "created", "assigned", "noted"
// or "closed"; detail is the state or outcome word only, never free text.
// ActorToken is filled by erasure the same way AuditEntry's is (B4-10):
// actor_id goes to 0, the token records that the acting principal erased.
type ReportEvent struct {
	ID         int64
	ReportID   int64
	ActorID    int64
	ActorToken string
	Action     string
	Detail     string
	CreatedAt  string
}

func reportFromRow(r dbgen.Report) Report {
	return Report{
		ID: r.ID, PublicID: r.PublicID, ReporterID: r.ReporterID, ReporterToken: strOrEmpty(r.ReporterToken),
		SubjectID: r.SubjectID, SubjectToken: strOrEmpty(r.SubjectToken),
		TargetType: r.TargetType, TargetRef: r.TargetRef, ChannelID: r.ChannelID,
		Reason: r.Reason, Detail: r.Detail, State: r.State, AssigneeID: r.AssigneeID,
		Outcome: r.Outcome, CreatedAt: r.CreatedAt, UpdatedAt: r.UpdatedAt, ClosedAt: r.ClosedAt,
	}
}

func strOrEmpty(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}

// FileReport inserts a report row, its evidence snapshot and its opening
// report_events row in ONE writer transaction (Codex review, P1-4, widened
// by a second review): several autocommits here would let an erasure that
// lands between the report insert and an evidence insert leave restored
// content or a since-erased author id in a row that EraseAccount already ran
// its unlink pass over. publicID is generated by the caller (crypto/rand,
// service layer) before this runs. A violation of idx_reports_active_unique
// (migration 048) — two simultaneous filings of the same reporter+target
// both reaching this INSERT — surfaces as db.ErrConflict. InsertReport's own
// EXISTS guards (a second review widening) turn a reporter or subject erased
// between the caller's resolution and this transaction into a zero-row
// RETURNING, surfaced here as db.ErrNotFound. An evidence row whose author
// was erased in that same window is silently dropped (its own guard), not
// an abort — the snapshot is simply short one context row, the same
// shape the retention sweep already leaves behind.
func (d *DB) FileReport(ctx context.Context, publicID string, reporterID, subjectID int64, targetType, targetRef string, channelID *int64, reason, detail string, evidence []ReportEvidenceInput) (int64, error) {
	tx, err := d.writer.BeginTx(ctx, nil)
	if err != nil {
		return 0, fmt.Errorf("FileReport begin tx: %w", err)
	}
	defer tx.Rollback() //nolint:errcheck
	q := dbgen.New(tx)

	id, err := q.InsertReport(ctx, dbgen.InsertReportParams{
		PublicID: publicID, ReporterID: reporterID, SubjectID: subjectID, TargetType: targetType,
		TargetRef: targetRef, ChannelID: channelID, Reason: reason, Detail: detail,
	})
	if err != nil {
		if IsUniqueConstraintError(err) {
			return 0, fmt.Errorf("FileReport: %w", ErrConflict)
		}
		if errors.Is(err, sql.ErrNoRows) {
			return 0, fmt.Errorf("FileReport: reporter or subject no longer exists: %w", ErrNotFound)
		}
		return 0, fmt.Errorf("FileReport insert report: %w", err)
	}
	for _, e := range evidence {
		if err := q.InsertReportEvidence(ctx, dbgen.InsertReportEvidenceParams{
			ReportID: id, Seq: e.Seq, MessageID: e.MessageID, AuthorID: e.AuthorID,
			Content: e.Content, Attachments: e.AttachmentsJSON,
		}); err != nil {
			return 0, fmt.Errorf("FileReport insert evidence: %w", err)
		}
	}
	// The opening report_events row, in the same transaction: never the
	// shared audit_log (second Codex review), actor 0 (the system actor,
	// same reasoning as the removed report_create audit row: the reporter's
	// identity is already on the reports row itself, for the same
	// bit-holding readers to see — this column need not repeat it).
	if err := q.InsertReportEvent(ctx, dbgen.InsertReportEventParams{ReportID: id, ActorID: 0, Action: "created", Detail: reason}); err != nil {
		return 0, fmt.Errorf("FileReport insert event: %w", err)
	}
	if err := tx.Commit(); err != nil {
		return 0, fmt.Errorf("FileReport commit: %w", err)
	}
	return id, nil
}

// GetReport returns one report by id, or ErrNotFound.
func (d *DB) GetReport(ctx context.Context, id int64) (*Report, error) {
	r, err := d.q.GetReportByID(ctx, id)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, ErrNotFound
		}
		return nil, fmt.Errorf("GetReport: %w", err)
	}
	rep := reportFromRow(r)
	return &rep, nil
}

// GetReportByPublicID resolves the opaque public id every route parameter
// and API response carries to the report row, or ErrNotFound.
func (d *DB) GetReportByPublicID(ctx context.Context, publicID string) (*Report, error) {
	r, err := d.q.GetReportByPublicID(ctx, publicID)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, ErrNotFound
		}
		return nil, fmt.Errorf("GetReportByPublicID: %w", err)
	}
	rep := reportFromRow(r)
	return &rep, nil
}

// FindOpenOrAssignedReport is the duplicate-report FAST-PATH check: the same
// reporter, same target, an open or assigned report already exists.
// Returns 0, nil when none does. This alone is not race-proof — see
// idx_reports_active_unique, which FileReport's constraint-violation
// mapping actually enforces.
func (d *DB) FindOpenOrAssignedReport(ctx context.Context, reporterID int64, targetType, targetRef string) (int64, error) {
	id, err := d.q.FindOpenOrAssignedReport(ctx, dbgen.FindOpenOrAssignedReportParams{
		ReporterID: reporterID, TargetType: targetType, TargetRef: targetRef,
	})
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return 0, nil
		}
		return 0, fmt.Errorf("FindOpenOrAssignedReport: %w", err)
	}
	return id, nil
}

