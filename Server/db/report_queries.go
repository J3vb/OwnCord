// AssignReport assigns assigneeID to report id, guarded on state,
// observedAssigneeID (optimistic concurrency: a concurrent reassignment moves
// it, so a racing caller's outrank verdict computed against the stale value
// is never applied) and EXISTS(users) (an erased moderator cannot land as the
// assignee). It returns false on a conflict for any of the three.
func (d *DB) AssignReport(ctx context.Context, id, assigneeID, observedAssigneeID int64) (bool, error) {
	return d.reportMutation(ctx, "AssignReport", id, assigneeID, "assigned", "", func(q *dbgen.Queries) (int64, error) {
		return q.AssignReport(ctx, dbgen.AssignReportParams{AssigneeID: assigneeID, ID: id, ObservedAssigneeID: observedAssigneeID})
	})
}

// forceReassignInTxHook runs inside forceReassignGuarded's transaction right
// after BeginTx, before the fresh reads it guards, and receives that
// transaction's Queries so a test can mutate state on the same tx. Test-only.
var forceReassignInTxHook func(ctx context.Context, q *dbgen.Queries) error

// forceReassignGuarded is the machinery behind AssignReportForced and
// AssignAppealForced. Both principals' role positions are read through this
// transaction's connection immediately before doUpdate runs, so a demotion
// racing the caller's earlier read cannot force-reassign with a rank the actor
// no longer holds. It returns (true, nil) on success, (false, nil) for the
// ordinary state/observed/existence conflict doUpdate's guard covers
// (including either principal no longer resolving to a role), and (false,
// ErrForbidden) when the actor's fresh position does not outrank the
// assignee's; callers map that to 403, distinct from the 409 conflict.
//
// checkAuthority, when non-nil, re-checks the actor's own moderation
// authority (CanModerate bit, effective ban) in the transaction. checkSelfReview,
// when non-nil, is the deciding-moderator eligibility test; refuse=true means
// another eligible moderator exists and self-assignment fails with
// ErrSelfReview. Nil skips each (reports never asked for either).
func forceReassignGuarded(ctx context.Context, writer *sql.DB, actorID, observedAssigneeID int64,
	checkAuthority func(rolePerms int64, banned bool, banExpires *string) error,
	checkSelfReview func(q *dbgen.Queries) (refuse bool, err error),
	doUpdate func(*dbgen.Queries) (int64, error)) (bool, error) {
	tx, err := writer.BeginTx(ctx, nil)
	if err != nil {
		return false, fmt.Errorf("forceReassignGuarded begin tx: %w", err)
	}
	defer tx.Rollback() //nolint:errcheck
	q := dbgen.New(tx)

	if forceReassignInTxHook != nil {
		if err := forceReassignInTxHook(ctx, q); err != nil {
			return false, fmt.Errorf("forceReassignGuarded test hook: %w", err)
		}
	}

	if checkAuthority != nil {
		rolePerms, banned, banExpires, ok := deciderAuthority(ctx, tx, actorID)
		if !ok || checkAuthority(rolePerms, banned, banExpires) != nil {
			return false, fmt.Errorf("forceReassignGuarded: %w", ErrForbidden)
		}
	}
	if checkSelfReview != nil {
		refuse, err := checkSelfReview(q)
		if err != nil {
			return false, fmt.Errorf("forceReassignGuarded self-review: %w", err)
		}
		if refuse {
			return false, ErrSelfReview
		}
	}

	actorPos, ok := rolePosition(ctx, tx, actorID)
	if !ok {
		return false, fmt.Errorf("forceReassignGuarded: %w", ErrForbidden)
	}
	targetRole, err := q.GetRoleForUser(ctx, observedAssigneeID)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return false, nil
		}
		return false, fmt.Errorf("forceReassignGuarded role lookup: %w", err)
	}
	if int64(actorPos) <= targetRole.Position {
		return false, ErrForbidden
	}

	n, err := doUpdate(q)
	if err != nil {
		return false, fmt.Errorf("forceReassignGuarded: %w", err)
	}
	if n != 1 {
		return false, nil
	}
	if err := tx.Commit(); err != nil {
		return false, fmt.Errorf("forceReassignGuarded commit: %w", err)
	}
	return true, nil
}

// AssignReportForced is the report queue's force-reassign path; see
// forceReassignGuarded.
func (d *DB) AssignReportForced(ctx context.Context, id, assigneeID, observedAssigneeID, actorID int64) (bool, error) {
	return forceReassignGuarded(ctx, d.writer, actorID, observedAssigneeID, nil, nil, func(q *dbgen.Queries) (int64, error) {
		n, err := q.AssignReport(ctx, dbgen.AssignReportParams{AssigneeID: assigneeID, ID: id, ObservedAssigneeID: observedAssigneeID})
		if err != nil || n != 1 {
			return n, err
		}
		return n, q.InsertReportEvent(ctx, dbgen.InsertReportEventParams{ReportID: id, ActorID: actorID, Action: "assigned"})
	})
}

// CloseReport closes report id with outcome (state "resolved" or "dismissed"),
// guarded to open/assigned and EXISTS(users) for actorID, and records the
// "closed" event in the same transaction. It returns false on a conflict.
