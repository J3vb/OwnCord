// ListReportsQueue returns the queue for one state filter: "open", "assigned",
// "closed" (every terminal state), or "" for open plus assigned.
func (d *DB) ListReportsQueue(ctx context.Context, state string) ([]ReportQueueRow, error) {
	switch state {
	case "open", "assigned":
		rows, err := d.q.ListReportsByState(ctx, state)
		if err != nil {
			return nil, fmt.Errorf("ListReportsQueue: %w", err)
		}
		out := make([]ReportQueueRow, 0, len(rows))
		for i := range rows {
			r := &rows[i]
			out = append(out, queueRowFrom(r.ID, r.PublicID, r.ReporterID, r.SubjectID, r.TargetType, r.TargetRef,
				r.ChannelID, r.Reason, r.State, r.AssigneeID, r.Outcome, r.CreatedAt, r.UpdatedAt,
				r.ClosedAt, r.ReporterName, r.SubjectName))
		}
		return out, nil
	case "closed":
		rows, err := d.q.ListReportsClosed(ctx)
		if err != nil {
			return nil, fmt.Errorf("ListReportsQueue: %w", err)
		}
		out := make([]ReportQueueRow, 0, len(rows))
		for i := range rows {
			r := &rows[i]
			out = append(out, queueRowFrom(r.ID, r.PublicID, r.ReporterID, r.SubjectID, r.TargetType, r.TargetRef,
				r.ChannelID, r.Reason, r.State, r.AssigneeID, r.Outcome, r.CreatedAt, r.UpdatedAt,
				r.ClosedAt, r.ReporterName, r.SubjectName))
		}
		return out, nil
	default:
		rows, err := d.q.ListReportsOpenOrAssigned(ctx)
		if err != nil {
			return nil, fmt.Errorf("ListReportsQueue: %w", err)
		}
		out := make([]ReportQueueRow, 0, len(rows))
		for i := range rows {
			r := &rows[i]
			out = append(out, queueRowFrom(r.ID, r.PublicID, r.ReporterID, r.SubjectID, r.TargetType, r.TargetRef,
				r.ChannelID, r.Reason, r.State, r.AssigneeID, r.Outcome, r.CreatedAt, r.UpdatedAt,
				r.ClosedAt, r.ReporterName, r.SubjectName))
		}
		return out, nil
	}
}

