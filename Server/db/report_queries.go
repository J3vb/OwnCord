// Report is a row of the reports table (migration 048, B5-8). ReporterToken
// and SubjectToken are filled by erasure (the audit_log two-token pattern,
// migrations 038/041): a zero id plus a non-empty token means that principal
// erased their account. PublicID is the only identifier ever exposed
// outside the server — the sequential ID is internal (foreign keys, audit
// target_id) and must never reach an API response, a route parameter or a
// mod_queue frame (Codex review: a bit holder who can see reports 1 and 3
// but never 2 in any queue view they can read infers report 2 is about
// them).
type Report struct {
	ID            int64
	PublicID      string
	ReporterID    int64
	ReporterToken string
	SubjectID     int64
	SubjectToken  string
	TargetType    string
	TargetRef     string
	ChannelID     *int64
	Reason        string
	Detail        string
	State         string
	AssigneeID    int64
	Outcome       string
	CreatedAt     string
	UpdatedAt     string
	ClosedAt      *string
}

// ReportQueueRow is one row of the moderation queue listing, with reporter
// and subject usernames resolved for display. Never carries the reason
// detail's free text or the evidence/notes.
type ReportQueueRow struct {
	ID           int64
	PublicID     string
	ReporterID   int64
	SubjectID    int64
	TargetType   string
	TargetRef    string
	ChannelID    *int64
	Reason       string
	State        string
	AssigneeID   int64
	Outcome      string
	CreatedAt    string
	UpdatedAt    string
	ClosedAt     *string
	ReporterName string
	SubjectName  string
}

// ReportSummary is one row of a reporter's own view (GET /api/v1/reports/mine):
// never the assignee, never the notes.
type ReportSummary struct {
	ID         int64
	PublicID   string
	TargetType string
	Reason     string
	State      string
	Outcome    string
	CreatedAt  string
	ClosedAt   *string
}

