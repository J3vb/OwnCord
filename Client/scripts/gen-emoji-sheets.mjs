#!/usr/bin/env node
// Generates the emoji picker's image sheets — src/assets/emoji-sheets/*.webp —
// and src/features/messaging/emojiSheetsData.ts from the Twemoji SVGs in
// @discordapp/twemoji and the catalog in src/features/messaging/emojiData.ts.
//
// From Client/ (needs Playwright's Chromium, which draws and encodes the sheets;
// OWNCORD_CHROMIUM names another Chromium binary):
//   node scripts/gen-emoji-sheets.mjs
//
// One sheet per catalog group, without skin tones: the picker draws a toned
// sheet itself the first time someone picks that tone (toneSheets.ts), which
// keeps the installer small. A sheet holds its group's emoji in catalog order, eight to a
// row (the picker's own grid), CELL px square, so the picker finds an emoji's
// cell from its index alone and needs no position table. The generated module
// records a hash of the catalog: emojiSheets.test.ts fails when the catalog
// changes without the sheets being regenerated.
//
// Re-run after bumping @discordapp/twemoji or regenerating emojiData.ts. The
// script fails if a catalog emoji, in any skin tone, has no Twemoji image.

import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { EMOJI_GROUPS } from "../src/features/messaging/emojiData.ts";
import { twemojiFileName } from "./twemoji-names.mjs";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");

const CELL = 48;
const COLUMNS = 8;
const QUALITY = 0.8;
const SKIN_TONES = ["", "\u{1F3FB}", "\u{1F3FC}", "\u{1F3FD}", "\u{1F3FE}", "\u{1F3FF}"];

const SVG_DIR = fileURLToPath(
  new URL("../node_modules/@discordapp/twemoji/dist/svg/", import.meta.url),
);
const OUT_DIR = fileURLToPath(new URL("../src/assets/emoji-sheets/", import.meta.url));
const OUT_TS = new URL("../src/features/messaging/emojiSheetsData.ts", import.meta.url);

/** Mirrors withSkinTone() in emojiCatalog.ts. */
function withSkinTone(char, toneSegments, tone) {
  const mod = SKIN_TONES[tone];
  if (!mod || toneSegments === "") return char;
  const segs = char.split("‍");
  for (const i of toneSegments) {
    const seg = segs[Number(i)] ?? "";
    const first = String.fromCodePoint(seg.codePointAt(0) ?? 0);
    segs[Number(i)] = first + mod + seg.slice(first.length).replace("️", "");
  }
  return segs.join("‍");
}

const files = new Map();
for (const f of readdirSync(SVG_DIR)) {
  if (f.endsWith(".svg")) files.set(twemojiFileName(f.slice(0, -4)), f);
}

const sheets = [];
for (const [group, rows] of EMOJI_GROUPS) {
  const entries = rows.split("\n").map((row) => row.split("|"));
  const toneable = entries.some(([, tone]) => tone !== "");
  for (let tone = 0; tone < (toneable ? SKIN_TONES.length : 1); tone++) {
    const svgs = entries.map(([char, segments]) => {
      const emoji = withSkinTone(char, segments, tone);
      const file = files.get(twemojiFileName(emoji));
      if (file === undefined) throw new Error(`no Twemoji image for ${emoji}`);
      return readFileSync(SVG_DIR + file, "utf8");
    });
    if (tone === 0) sheets.push({ name: group, svgs });
  }
}

const browser = await chromium.launch(
  process.env.OWNCORD_CHROMIUM ? { executablePath: process.env.OWNCORD_CHROMIUM } : {},
);
const page = await browser.newPage();
rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });
let total = 0;
for (const sheet of sheets) {
  const dataUrl = await page.evaluate(
    async ({ svgs, cell, columns, quality }) => {
      const canvas = document.createElement("canvas");
      canvas.width = columns * cell;
      canvas.height = Math.ceil(svgs.length / columns) * cell;
      const ctx = canvas.getContext("2d");
      await Promise.all(
        svgs.map(async (svg, i) => {
          const img = new Image(cell, cell);
          img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
          await img.decode();
          ctx.drawImage(img, (i % columns) * cell, Math.floor(i / columns) * cell, cell, cell);
        }),
      );
      return canvas.toDataURL("image/webp", quality);
    },
    { svgs: sheet.svgs, cell: CELL, columns: COLUMNS, quality: QUALITY },
  );
  const bytes = Buffer.from(dataUrl.slice(dataUrl.indexOf(",") + 1), "base64");
  writeFileSync(`${OUT_DIR}${sheet.name}.webp`, bytes);
  total += bytes.length;
}
await browser.close();

const hash = createHash("sha256").update(JSON.stringify(EMOJI_GROUPS)).digest("hex").slice(0, 16);
const imports = sheets
  .map((s, i) => `import sheet${i} from "../../assets/emoji-sheets/${s.name}.webp";`)
  .join("\n");
const entries = sheets.map((s, i) => `  ${JSON.stringify(s.name)}: sheet${i},`).join("\n");
writeFileSync(
  OUT_TS,
  `// Generated by scripts/gen-emoji-sheets.mjs from @discordapp/twemoji and emojiData.ts. Do not edit.
// Twemoji graphics: Copyright Twitter, Inc. and other contributors, CC-BY 4.0.

${imports}

/** Hash of the emoji catalog the sheets were drawn from (see emojiSheets.test.ts). */
export const SHEETS_CATALOG_HASH = "${hash}";

/** Each group's sheet URL, by group key. */
export const EMOJI_SHEETS: Readonly<Record<string, string>> = {
${entries}
};
`,
);
console.log(`${sheets.length} sheets, ${(total / 1024).toFixed(0)} KB`);
