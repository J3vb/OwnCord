// One explicit file list per shard. Explicit lists (not globs) are what makes
// the union check in scripts/check-mutation-shards.mjs exact: the union of
// every shard must equal the base config's configured surface, so no file can
// silently drop out of the nightly baseline.
//
// Sizing: the 90-minute job ceiling is fixed, and GitHub's runners differ in
// speed by up to ~1.5x from job to job (one shard with unchanged files took
// 58 minutes of mutation work one night and ~85 the next). So shards are
// sized for ~38 minutes of mutation work, which stays under 90 with the dry
// run (up to ~12 minutes) on a slow one. Each file's cost is its share of its
// shard's mutants times that shard's measured mutation minutes in run
// 43140439761 (2026-11-12, 62 shards); the two shards that stopped in the dry
// run that night use their area's median minutes per mutant. Within each
// area, files are packed largest first into the lightest shard. The workflow
// reads the shard names from this object, so adding a shard here adds a
// matrix job.

