/**
 * No non-test source file under Client/src is longer than 1,200 lines.
 *
 * A file past that size no longer fits in one read, for a person or an agent,
 * so a change gets made against a part of the file that was never seen. The
 * files that were already over the limit when this test arrived are listed in
 * file-sizes.json with a ceiling: their size rounded up to the next 50. The
 * list is a ratchet. A ceiling only goes down, a file that shrinks 50 lines
 * below its ceiling gets the ceiling lowered, a file back under the limit
 * leaves the list, and no file is ever added. Split a file that grows instead.
 *
 * Files a script writes (data tables marked "Generated by" on their first
 * line) are not read by hand, so they are exempt; that list only shrinks too.
 */
import { describe, it, expect } from "vitest";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const CLIENT = resolve(__dirname, "../..");
const SRC = join(CLIENT, "src");
const MAX_LINES = 1200;
const STEP = 50;

/** Files still over the limit. Lower this with every file that leaves the list; it never rises. */
const OVER_LIMIT_CAP = 6;

/** Generated data files, exempt from the limit. Never add a hand-written file here. */
const GENERATED = new Set(["src/features/messaging/emojiData.ts"]);

const ceilings = JSON.parse(readFileSync(join(__dirname, "file-sizes.json"), "utf8")) as Record<
  string,
  number
>;

function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(path);
    const isSource = /\.m?ts$/.test(entry.name) && !entry.name.endsWith(".d.ts");
    return isSource && !entry.name.endsWith(".test.ts") ? [path] : [];
  });
}

function lineCount(path: string): number {
  const text = readFileSync(path, "utf8");
  if (text === "") return 0;
  return text.endsWith("\n") ? text.split("\n").length - 1 : text.split("\n").length;
}

const sizes = new Map(
  sourceFiles(SRC)
    .map((path) => [relative(CLIENT, path).split("\\").join("/"), lineCount(path)] as const)
    .filter(([file]) => !GENERATED.has(file)),
);

describe("source file size", () => {
  it("finds the source files it is meant to measure", () => {
    expect(sizes.size).toBeGreaterThan(300);
  });

  it(`keeps every source file at ${MAX_LINES} lines or its listed ceiling`, () => {
    const tooLong = [...sizes]
      .filter(([file, lines]) => lines > (ceilings[file] ?? MAX_LINES))
      .map(([file, lines]) => `${file} (${lines} lines, cap ${ceilings[file] ?? MAX_LINES})`);
    expect(tooLong).toEqual([]);
  });

  it("lists only files that exist and are still over the limit", () => {
    const stale = Object.keys(ceilings).filter(
      (file) => !existsSync(join(CLIENT, file)) || (sizes.get(file) ?? 0) <= MAX_LINES,
    );
    expect(stale).toEqual([]);
  });

  it("lowers a ceiling once its file has shrunk by a step", () => {
    const loose = Object.entries(ceilings)
      .filter(([file, ceiling]) => ceiling - (sizes.get(file) ?? 0) >= STEP)
      .map(([file, ceiling]) => {
        const lines = sizes.get(file) ?? 0;
        return `${file}: set ${Math.ceil(lines / STEP) * STEP} (was ${ceiling})`;
      });
    expect(loose).toEqual([]);
  });

  it("never lets the list grow", () => {
    expect(Object.keys(ceilings).length).toBeLessThanOrEqual(OVER_LIMIT_CAP);
  });

  it("exempts only files a generator wrote", () => {
    const handWritten = [...GENERATED].filter(
      (file) =>
        !existsSync(join(CLIENT, file)) ||
        !readFileSync(join(CLIENT, file), "utf8").startsWith("// Generated by"),
    );
    expect(handWritten).toEqual([]);
    expect(GENERATED.size).toBeLessThanOrEqual(1);
  });
});
